//! Code and script emission (R24): the system crate manifest (`CONFIG`,
//! `LAYOUT`, the `System` implementation), each Partition's manifest
//! (Resource cells, Context types, Job wrappers), the linker script with
//! its memory map (DD-07, DD-11), and the human-readable configuration
//! summary (R24.3). The emitted Rust contains no `unsafe` (R24.2): the
//! Resource cells use `rsk::ResourceCell`, whose `unsafe impl Sync` is
//! justified in the Kernel_Unsafe_Module (UJ-050).

use std::fmt::Write;

use crate::derive::{Generated, Kind, ReleaseSource, NO_SLOT};
use crate::layout::Region;
use crate::model::cs_sites;

fn resp(code: u8) -> &'static str {
    match code {
        0 => "RESP_END_JOB",
        1 => "RESP_RESTART_PARTITION",
        2 => "RESP_STOP_PARTITION",
        3 => "RESP_SAFE_STATE",
        4 => "RESP_RECORD_ONLY",
        _ => "RESP_RECORD_AND_CONTINUE",
    }
}

fn interval(r: &Region) -> String {
    format!("Interval {{ base: 0x{:08x}, size_log2: {} }}", r.base, r.size_log2)
}

/// The system crate manifest (expanded by `rsk_system!()` in the system
/// crate, which depends on `rsk-kernel` and every Partition crate).
pub fn system_source(g: &Generated) -> String {
    let nt = g.tasks.len();
    let nr = g.resources.len();
    let np = g.partitions.len();
    let mut s = String::new();
    let _ = writeln!(s, "// @generated by rsk-gen (Generated_Config, R24.1). Do not edit.");
    let _ = writeln!(s, "pub const NT: usize = {nt};");
    let _ = writeln!(s, "pub const NR: usize = {nr};");
    let _ = writeln!(s, "pub const NP: usize = {np};");
    let _ = writeln!(s, "pub const NL: usize = {};", g.lock_capacity);
    let _ = writeln!(s, "pub const NS: usize = {};", g.slot_count);
    let _ = writeln!(s, "pub const NE: usize = {};", g.log_capacity);
    let _ = writeln!(s, "/// Time-base ticks per second (R21.2).");
    let _ = writeln!(s, "pub const TICK_HZ: u64 = {};", g.target.tick_hz);
    let _ = writeln!(s, "pub const CPU_HZ: u64 = {};", g.target.cpu_hz);
    let _ = writeln!(s, "pub const CONFIG_CHECKSUM: u32 = 0x{:08x};", g.checksum);
    // The canonical table image and the checksum as link-level symbols, for
    // the Config_Checker's extraction from the binary (R26.4). `#[used]`
    // keeps them through section garbage collection; `no_mangle` is not an
    // unsafe attribute in the 2021 edition, so the system crate keeps
    // `#![forbid(unsafe_code)]` (R24.2).
    let image = crate::derive::config_bytes(g);
    let _ = writeln!(s, "/// Canonical image of the tables above (the bytes the checksum covers).");
    let _ = writeln!(s, "#[used]");
    let _ = writeln!(s, "#[no_mangle]");
    let _ = writeln!(s, "pub static RSK_CONFIG_IMAGE: [u8; {}] = [{}];", image.len(), image.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", "));
    let _ = writeln!(s, "#[used]");
    let _ = writeln!(s, "#[no_mangle]");
    let _ = writeln!(s, "pub static RSK_CONFIG_CHECKSUM: u32 = CONFIG_CHECKSUM;");
    // The LAYOUT image and checksum (R24.1, R12.3): the Kernel compares the
    // checksum of its LAYOUT with LAYOUT_CHECKSUM at boot; the Config_Checker
    // compares the image with the Task_Model and the checksum (R26.4).
    let layout_image = crate::derive::layout_bytes(g);
    let _ = writeln!(s, "pub const LAYOUT_CHECKSUM: u32 = 0x{:08x};", crate::derive::layout_checksum(g));
    let _ = writeln!(s, "/// Canonical image of `LAYOUT` (the bytes `LAYOUT_CHECKSUM` covers).");
    let _ = writeln!(s, "#[used]");
    let _ = writeln!(s, "#[no_mangle]");
    let _ = writeln!(s, "pub static RSK_LAYOUT_IMAGE: [u8; {}] = [{}];", layout_image.len(), layout_image.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", "));
    let _ = writeln!(s, "#[used]");
    let _ = writeln!(s, "#[no_mangle]");
    let _ = writeln!(s, "pub static RSK_LAYOUT_CHECKSUM: u32 = LAYOUT_CHECKSUM;");
    let _ = writeln!(s, "pub const CONFIG: ::rsk_kernel::logic::Config<NT, NR, NP> = ::rsk_kernel::logic::Config {{");
    let _ = writeln!(s, "    tasks: [");
    for t in &g.tasks {
        let _ = writeln!(
            s,
            "        ::rsk_kernel::logic::TaskCfg {{ priority: {}, partition: {}, kind: {}, offset: {}, period: {}, deadline: {}, budget: {}, mit_policy: {}, fpu: {} }}, // {}",
            t.priority,
            t.partition,
            if t.kind == Kind::Periodic { "::rsk_kernel::logic::KIND_PERIODIC" } else { "::rsk_kernel::logic::KIND_SPORADIC" },
            t.offset_ticks,
            t.period_ticks,
            t.deadline_ticks,
            t.budget_cycles,
            match t.mit_policy {
                crate::decl::MitPolicy::Defer => "::rsk_kernel::logic::MIT_DEFER",
                crate::decl::MitPolicy::Discard => "::rsk_kernel::logic::MIT_DISCARD",
            },
            t.fpu,
            t.id
        );
    }
    let _ = writeln!(s, "    ],");
    let _ = writeln!(s, "    resources: [");
    for r in &g.resources {
        let _ = writeln!(s, "        ::rsk_kernel::logic::ResourceCfg {{ ceiling: {}, partition: {} }}, // {}", r.ceiling, r.partition, r.id);
    }
    let _ = writeln!(s, "    ],");
    let _ = writeln!(s, "    access: [");
    for t in &g.tasks {
        let row: Vec<&str> = (0..nr).map(|r| if t.resources.contains(&r) { "true" } else { "false" }).collect();
        let _ = writeln!(s, "        [{}],", row.join(", "));
    }
    let _ = writeln!(s, "    ],");
    let _ = writeln!(s, "    partitions: [");
    for p in &g.partitions {
        let _ = writeln!(
            s,
            "        ::rsk_kernel::logic::PartitionCfg {{ level: {}, fault_response: ::rsk_kernel::logic::{}, overrun_response: ::rsk_kernel::logic::{}, deadline_response: ::rsk_kernel::logic::{}, mit_threshold: {} }}, // {}",
            p.level.code(),
            resp(p.fault.code()),
            resp(p.overrun.code()),
            resp(p.deadline_miss.code()),
            p.mit_threshold,
            p.name
        );
    }
    let _ = writeln!(s, "    ],");
    let _ = writeln!(s, "    operating_duration: {},", g.operating_duration_ticks);
    let slots = |f: fn(&crate::derive::GenTask) -> u8| -> String {
        g.tasks.iter().map(|t| if f(t) == NO_SLOT { "::rsk_kernel::logic::NO_SLOT".to_string() } else { f(t).to_string() }).collect::<Vec<_>>().join(", ")
    };
    let _ = writeln!(s, "    slot_release: [{}],", slots(|t| t.slot_release));
    let _ = writeln!(s, "    slot_deadline: [{}],", slots(|t| t.slot_deadline));
    let _ = writeln!(s, "    slot_budget: [{}],", slots(|t| t.slot_budget));
    let _ = writeln!(s, "    slot_count: NS as u8,");
    let _ = writeln!(s, "}};");
    // Layout.
    let _ = writeln!(s, "use ::rsk_kernel::logic::mpu::{{Interval, Layout, PartitionLayout}};");
    let _ = writeln!(s, "const NO_WINDOW: Interval = Interval {{ base: 0, size_log2: 5 }};");
    let _ = writeln!(s, "pub const LAYOUT: Layout<NP> = Layout {{");
    let _ = writeln!(s, "    kernel_flash: {},", interval(&g.plan.kernel_flash));
    let _ = writeln!(s, "    shared_code: {},", interval(&g.plan.shared_code));
    let _ = writeln!(s, "    kernel_ram: {},", interval(&g.plan.kernel_ram));
    let mut kwins: Vec<String> = g.plan.kernel_windows.iter().map(|w| format!("Interval {{ base: 0x{:08x}, size_log2: {} }}", w.base, w.size_log2)).collect();
    while kwins.len() < crate::layout::MAX_KERNEL_WINDOWS {
        kwins.push("NO_WINDOW".to_string());
    }
    let _ = writeln!(s, "    // R16.2: {}", g.plan.kernel_windows.iter().map(|w| w.peripherals.join(",")).collect::<Vec<_>>().join(", "));
    let _ = writeln!(s, "    kernel_windows: [{}],", kwins.join(", "));
    let _ = writeln!(s, "    kernel_window_count: {},", g.plan.kernel_windows.len());
    let _ = writeln!(s, "    partitions: [");
    for p in &g.plan.partitions {
        let mut windows: Vec<String> = p.windows.iter().map(|w| format!("Interval {{ base: 0x{:08x}, size_log2: {} }}", w.base, w.size_log2)).collect();
        while windows.len() < crate::layout::MAX_WINDOWS {
            windows.push("NO_WINDOW".to_string());
        }
        let _ = writeln!(
            s,
            "        PartitionLayout {{ code: {}, code_srd: 0x{:02x}, ram: {}, ram_srd: 0x{:02x}, stack_size: {}, windows: [{}], window_count: {} }}, // {}",
            interval(&p.code),
            p.code.srd,
            interval(&p.ram),
            p.ram.srd,
            p.stack,
            windows.join(", "),
            p.windows.len(),
            p.name
        );
    }
    let _ = writeln!(s, "    ],");
    let _ = writeln!(s, "}};");
    let _ = writeln!(s, "pub type K = ::rsk_kernel::arch::Bound<NT, NR, NP, NL, NS, NE>;");
    let views: Vec<&str> = (0..np).map(|_| "::rsk_kernel::arch::placeholder_view()").collect();
    let _ = writeln!(
        s,
        "static KERNEL: ::rsk_kernel::arch::cm4::KernelCell<K> = ::rsk_kernel::arch::cm4::KernelCell::new(::rsk_kernel::arch::Bound {{ cfg: CONFIG, kernel: ::rsk_kernel::arch::placeholder_kernel(), layout: LAYOUT, views: [{}] }});",
        views.join(", ")
    );
    let dispatch: Vec<String> = g.tasks.iter().map(|t| t.dispatch_irq.to_string()).collect();
    let _ = writeln!(s, "const DISPATCH_IRQ: [u16; NT] = [{}];", dispatch.join(", "));
    let intake: Vec<String> = g
        .tasks
        .iter()
        .map(|t| match &t.source {
            Some(ReleaseSource::Interrupt { irq, .. }) => irq.to_string(),
            _ => "0xFFFF".to_string(),
        })
        .collect();
    let _ = writeln!(s, "const INTAKE_IRQ: [u16; NT] = [{}];", intake.join(", "));
    // EasyDMA channels (DD-08): one entry per channel of every EasyDMA
    // peripheral a Partition owns, in Partition order then peripheral name
    // order (the order of the summary), for `rsk::dma_request`.
    let mut dma: Vec<String> = Vec::new();
    for (pi, p) in g.plan.partitions.iter().enumerate() {
        for w in &p.windows {
            for name in &w.peripherals {
                let Some(per) = g.target.peripheral(name) else { continue };
                let Some(regs) = per.dma else { continue };
                let stop = |k: usize| regs.stops.get(k).map_or(0, |o| per.window_base + o);
                let list = |k: usize| regs.lists.get(k).map_or(0, |o| per.window_base + o);
                for (ptr, cnt) in regs.channels {
                    dma.push(format!(
                        "::rsk_kernel::arch::DmaCfg {{ partition: {pi}, ptr: 0x{:08x}, maxcnt: 0x{:08x}, stops: [0x{:08x}, 0x{:08x}], lists: [0x{:08x}, 0x{:08x}], shorts: 0x{:08x} }}, // {name}",
                        per.window_base + ptr,
                        if *cnt == 0 { 0 } else { per.window_base + cnt },
                        stop(0), stop(1), list(0), list(1),
                        if regs.shorts == 0 { 0 } else { per.window_base + regs.shorts }
                    ));
                }
            }
        }
    }
    let _ = writeln!(s, "pub const ND: usize = {};", dma.len());
    let _ = writeln!(s, "const NO_DMA: ::rsk_kernel::arch::DmaCfg = ::rsk_kernel::arch::DmaCfg {{ partition: 0xFF, ptr: 0, maxcnt: 0, stops: [0, 0], lists: [0, 0], shorts: 0 }};");
    let _ = writeln!(s, "pub const DMA: [::rsk_kernel::arch::DmaCfg; ND] = [");
    for d in &dma {
        let _ = writeln!(s, "    {d}");
    }
    let _ = writeln!(s, "];");
    // Release_Signals (R10.5): one entry per signal in Partition then
    // declaration order (the order of the Task_Model), with the declaring
    // Partition and the bound Sporadic_Task.
    let sigs = signals(g);
    let _ = writeln!(s, "pub const NSIG: usize = {};", sigs.len());
    let _ = writeln!(s, "const NO_SIGNAL: ::rsk_kernel::arch::SignalCfg = ::rsk_kernel::arch::SignalCfg {{ partition: 0xFF, task: 0xFF }};");
    let _ = writeln!(s, "pub const SIGNALS: [::rsk_kernel::arch::SignalCfg; NSIG] = [");
    for (p, name, task) in &sigs {
        let _ = writeln!(
            s,
            "    ::rsk_kernel::arch::SignalCfg {{ partition: {p}, task: {} }}, // {}.{name}",
            task.map_or("0xFF".to_string(), |t| t.to_string()),
            g.partitions[*p].name
        );
    }
    let _ = writeln!(s, "];");
    // Endpoints (task 21.2; R40.1, DD-09): the table, the Kernel-owned
    // storage of every channel (one static in the Kernel's RAM), and the
    // table's image for the Config_Checker.
    let _ = writeln!(s, "pub const NEP: usize = {};", g.endpoints.len());
    let _ = writeln!(s, "const NO_ENDPOINT: ::rsk_kernel::arch::EndpointCfg = ::rsk_kernel::arch::EndpointCfg {{ capacity: 0, payload: 0, tasks: [0xFF, 0xFF], partitions: [0xFF, 0xFF], release: [false, false], storage: 0 }};");
    let _ = writeln!(s, "pub const ENDPOINTS: [::rsk_kernel::arch::EndpointCfg; NEP] = [");
    for e in &g.endpoints {
        let task = |r: usize| e.roles.get(r).map_or("0xFF".to_string(), |(_, t)| t.to_string());
        let part = |r: usize| e.roles.get(r).map_or("0xFF".to_string(), |(_, t)| g.tasks[*t].partition.to_string());
        let _ = writeln!(
            s,
            "    ::rsk_kernel::arch::EndpointCfg {{ capacity: {}, payload: {}, tasks: [{}, {}], partitions: [{}, {}], release: [{}, {}], storage: {} }}, // {} ({}): {} => {}, {} => {}",
            e.capacity, e.payload, task(0), task(1), part(0), part(1), e.release[0], e.release[1], e.storage,
            e.name, e.ty,
            e.roles.first().map_or("", |(n, _)| n.as_str()), e.roles.first().map_or("", |(_, t)| g.tasks[*t].id.as_str()),
            e.roles.get(1).map_or("", |(n, _)| n.as_str()), e.roles.get(1).map_or("", |(_, t)| g.tasks[*t].id.as_str()),
        );
    }
    let _ = writeln!(s, "];");
    let _ = writeln!(s, "pub const ENDPOINT_STORAGE_BYTES: usize = {};", g.endpoint_storage_bytes);
    let _ = writeln!(s, "static ENDPOINT_STORAGE: ::rsk_kernel::arch::cm4::unsafe_module::hw::EndpointStorage<ENDPOINT_STORAGE_BYTES> = ::rsk_kernel::arch::cm4::unsafe_module::hw::EndpointStorage::new();");
    let eimage = crate::derive::endpoint_bytes(g);
    let _ = writeln!(s, "/// Canonical image of the Endpoint table, for the Config_Checker (R26.4).");
    let _ = writeln!(s, "#[used]");
    let _ = writeln!(s, "#[no_mangle]");
    let _ = writeln!(s, "pub static RSK_ENDPOINT_IMAGE: [u8; {}] = [{}];", eimage.len(), eimage.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", "));
    let _ = writeln!(s, "#[used]");
    let _ = writeln!(s, "#[no_mangle]");
    let _ = writeln!(s, "pub static RSK_ENDPOINT_CHECKSUM: u32 = 0x{:08x};", crate::derive::crc32(&eimage));
    let _ = writeln!(s, "pub struct Sys;");
    let _ = writeln!(s, "impl ::rsk_kernel::arch::System for Sys {{");
    let _ = writeln!(s, "    type K = K;");
    let _ = writeln!(s, "    const IRQ_COUNT: u16 = {};", g.target.irq_count);
    let _ = writeln!(s, "    const TIMER_VECTOR: u16 = 16 + {};", g.target.timer_irq);
    let _ = writeln!(s, "    const PRIORITY_BITS: u8 = {};", g.target.priority_bits);
    let _ = writeln!(s, "    const CPUID: u32 = 0x{:08x};", g.target.cpuid);
    let _ = writeln!(s, "    const HFCLK_XTAL: bool = {};", g.target.hfclk_xtal);
    let _ = writeln!(s, "    const FPU_NEEDED: bool = {};", g.tasks.iter().any(|t| t.fpu));
    let _ = writeln!(s, "    const FP_FLUSH_TO_ZERO: bool = {};", g.fp_flush_to_zero);
    let _ = writeln!(s, "    const TICK_HZ: u64 = {};", g.target.tick_hz);
    let _ = writeln!(s, "    const DMA_COUNT: usize = ND;");
    let _ = writeln!(s, "    fn dma(i: usize) -> ::rsk_kernel::arch::DmaCfg {{ if i < ND {{ DMA[i] }} else {{ NO_DMA }} }}");
    let _ = writeln!(s, "    const SIGNAL_COUNT: usize = NSIG;");
    let _ = writeln!(s, "    fn signal(i: usize) -> ::rsk_kernel::arch::SignalCfg {{ if i < NSIG {{ SIGNALS[i] }} else {{ NO_SIGNAL }} }}");
    let _ = writeln!(s, "    const ENDPOINT_COUNT: usize = NEP;");
    let _ = writeln!(s, "    fn endpoint(i: usize) -> ::rsk_kernel::arch::EndpointCfg {{ if i < NEP {{ ENDPOINTS[i] }} else {{ NO_ENDPOINT }} }}");
    let _ = writeln!(s, "    fn endpoint_storage() -> (u32, u32) {{ (ENDPOINT_STORAGE.base(), ENDPOINT_STORAGE.len()) }}");
    let _ = writeln!(s, "    const CONFIG_CHECKSUM: u32 = CONFIG_CHECKSUM;");
    let _ = writeln!(s, "    const LAYOUT_CHECKSUM: u32 = LAYOUT_CHECKSUM;");
    let _ = writeln!(s, "    fn kernel() -> &'static ::rsk_kernel::arch::cm4::KernelCell<K> {{ &KERNEL }}");
    let _ = writeln!(s, "    fn task_entry(t: u8) -> fn() {{");
    let _ = writeln!(s, "        match t {{");
    for t in &g.tasks {
        let _ = writeln!(s, "            {} => {},", t.index, t.entry_path);
    }
    let _ = writeln!(s, "            _ => {},", g.tasks[0].entry_path);
    let _ = writeln!(s, "        }}");
    let _ = writeln!(s, "    }}");
    let _ = writeln!(s, "    fn binding(n: u16) -> ::rsk_kernel::arch::Binding {{");
    let _ = writeln!(s, "        if n == Self::TIMER_VECTOR {{ return ::rsk_kernel::arch::Binding::Kernel; }}");
    let _ = writeln!(s, "        let mut t = 0;");
    let _ = writeln!(s, "        while t < NT {{");
    let _ = writeln!(s, "            if n == 16 + DISPATCH_IRQ[t] {{ return ::rsk_kernel::arch::Binding::Dispatch(t as u8); }}");
    let _ = writeln!(s, "            if INTAKE_IRQ[t] != 0xFFFF && n == 16 + INTAKE_IRQ[t] {{ return ::rsk_kernel::arch::Binding::Intake {{ task: t as u8, partition: CONFIG.tasks[t].partition }}; }}");
    let _ = writeln!(s, "            t += 1;");
    let _ = writeln!(s, "        }}");
    let _ = writeln!(s, "        ::rsk_kernel::arch::Binding::Unbound");
    let _ = writeln!(s, "    }}");
    let _ = writeln!(s, "    fn dispatch_vector(t: u8) -> u16 {{ 16 + DISPATCH_IRQ[t as usize] }}");
    let _ = writeln!(s, "    fn intake_vector(t: u8) -> Option<u16> {{ if INTAKE_IRQ[t as usize] == 0xFFFF {{ None }} else {{ Some(16 + INTAKE_IRQ[t as usize]) }} }}");
    let _ = writeln!(s, "    fn stack_top(p: u8) -> u32 {{ let pl = LAYOUT.partitions[p as usize]; pl.ram.base + pl.stack_size }}");
    let _ = writeln!(s, "    fn stack_bottom(p: u8) -> u32 {{ LAYOUT.partitions[p as usize].ram.base }}");
    let _ = writeln!(s, "    fn safe_state() -> ! {{ {}() }}", g.safe_state);
    let _ = writeln!(s, "}}");
    s
}

/// The manifest of one Partition crate (expanded by `rsk_partition_<name>!()`
/// at the crate root): the Resource cells, one Context type per Task with
/// a `Shared` proxy per accessed Resource (R8.7), and the Job wrappers
/// that the system crate's task table points at.
pub fn partition_source(g: &Generated, p: usize) -> String {
    let part = &g.partitions[p];
    let mut s = String::new();
    let _ = writeln!(s, "// @generated by rsk-gen for Partition `{}`. Do not edit.", part.name);
    // The cells and the Job wrappers are the glue the App_Prover does not
    // translate (Creusot rejects `static` items): under `cfg(creusot)` the
    // Task bodies and their Context types remain, the glue does not
    // (task 17.1, Verification_Plan section 7).
    let _ = writeln!(s, "#[cfg(not(creusot))]");
    let _ = writeln!(s, "pub mod rsk_resources {{");
    for &r in &part.resources {
        let res = &g.resources[r];
        let _ = writeln!(
            s,
            "    /// Resource `{}` (Ceiling {}; accessed by {}).",
            res.id,
            res.ceiling,
            res.accessors.iter().map(|&t| g.tasks[t].name.clone()).collect::<Vec<_>>().join(", ")
        );
        let _ = writeln!(s, "    pub static {}: ::rsk::ResourceCell<{}> = ::rsk::ResourceCell::new({});", res.name.to_uppercase(), res.ty, res.init);
    }
    let _ = writeln!(s, "}}");
    // Per-Task state (PR-25): one cell per declared item, `TASK_NAME`.
    let _ = writeln!(s, "#[cfg(not(creusot))]");
    let _ = writeln!(s, "pub mod rsk_state {{");
    for &t in &part.tasks {
        let task = &g.tasks[t];
        for st in &task.state {
            let _ = writeln!(s, "    /// Per-Task state `{}.{}` (PR-25): touched by `{}`'s Jobs only.", task.id, st.name, task.name);
            let _ = writeln!(s, "    pub static {}_{}: ::rsk::ResourceCell<{}> = ::rsk::ResourceCell::new({});", task.name.to_uppercase(), st.name.to_uppercase(), st.ty, st.init);
        }
        // Task 21.3 (R38.7): the RoleSlot of every Protocol role the Task is bound to.
        for (e, role) in protocol_roles(g, t) {
            let _ = writeln!(s, "    /// The RoleSlot of role `{role}` of Endpoint `{}` (task 21.3, R38.7): `{}`'s state between its Jobs.", e.name, task.name);
            let _ = writeln!(s, "    pub static {}_{}: ::rsk::ResourceCell<super::rsk_roles::{}_{role}::State> = ::rsk::ResourceCell::new(super::rsk_roles::{}_{role}::State::initial());", task.name.to_uppercase(), e.name.to_uppercase(), e.name, e.name);
        }
    }
    let _ = writeln!(s, "}}");
    // Task 21.3: the typestate role APIs of this Partition's Tasks; since
    // task 21.4 inside the App_Prover's translation too (the Kernel glue
    // they call is trusted in `rsk`, their own code is proven with the
    // bodies; the `Drop` report alone is outside it).
    let _ = writeln!(s, "pub mod rsk_roles {{");
    for &t in &part.tasks {
        for (e, role) in protocol_roles(g, t) {
            s.push_str(&crate::roles::module(g, e, &role));
        }
    }
    let _ = writeln!(s, "}}");
    // Task 21.4 (R42.4): the validators of the plain Endpoints' roles, each
    // binding the declared function to the `rsk::Validate` bound of the
    // Context's `Endpoint` field.
    let _ = writeln!(s, "pub mod rsk_validate {{");
    for &t in &part.tasks {
        for e in g.endpoints.iter().filter(|e| e.protocol.is_none()) {
            if let Some(ri) = e.roles.iter().position(|(_, ti)| *ti == t) {
                if let Some((_, path)) = e.validators.get(ri).and_then(|v| v.iter().find(|(l, _)| l.is_none())) {
                    let (role, _) = &e.roles[ri];
                    let _ = writeln!(s, "    /// The validation function of role `{role}` of Endpoint `{}` (R42.4): `{path}`.", e.name);
                    let _ = writeln!(s, "    #[allow(non_camel_case_types)]");
                    let _ = writeln!(s, "    pub struct {}_{role};", e.name);
                    let _ = writeln!(s, "    impl ::rsk::Validate<{}> for {}_{role} {{", e.ty, e.name);
                    let _ = writeln!(s, "        fn accept(m: &{}) -> bool {{ {path}(m) }}", e.ty);
                    let _ = writeln!(s, "    }}");
                }
            }
        }
    }
    let _ = writeln!(s, "}}");
    // The Target's clocks, so that a Task body states durations in time, not
    // in a board's ticks (the demo's busy waits; found on the nRF52840-DK,
    // 2026-10-29, where constants tuned for the QEMU board's 25 MHz time base
    // ran 1.6 times longer).
    let _ = writeln!(s, "/// The Target's clocks (R21.1): the time base `rsk::now()` counts, and the CPU.");
    let _ = writeln!(s, "pub mod rsk_target {{");
    let _ = writeln!(s, "    pub const TICK_HZ: u64 = {};", g.target.tick_hz);
    let _ = writeln!(s, "    pub const CPU_HZ: u64 = {};", g.target.cpu_hz);
    let _ = writeln!(s, "    /// Time-base ticks in `ms` milliseconds.");
    let _ = writeln!(s, "    /// Saturating, so the App_Prover has no overflow obligation (task 17.1).");
    let _ = writeln!(s, "    pub const fn ms(ms: u64) -> u64 {{ (TICK_HZ / 1000).saturating_mul(ms) }}");
    // The memory map (R16.8, task 7.4): the Kernel's, the shared code's,
    // and every Partition's regions as `(base, size)` and each Partition's
    // peripheral windows, so that the HIL isolation suite's access matrix
    // is generated from the same layout the MPU views are, not written by
    // hand. A Flight_Build's Task bodies have no use for it.
    let _ = writeln!(s, "    /// The memory map the MPU views are computed from (DD-07), for the HIL");
    let _ = writeln!(s, "    /// isolation suite (R16.8, task 7.4): `(base, size)` of each region.");
    let _ = writeln!(s, "    pub mod layout {{");
    let _ = writeln!(s, "        /// This Partition's index.");
    let _ = writeln!(s, "        pub const SELF: usize = {};", p);
    let _ = writeln!(s, "        pub const PARTITIONS: usize = {};", g.plan.partitions.len());
    let pair = |r: &crate::layout::Region| format!("(0x{:08x}, 0x{:x})", r.base, 1u64 << r.size_log2);
    let _ = writeln!(s, "        pub const KERNEL_FLASH: (u32, u32) = {};", pair(&g.plan.kernel_flash));
    let _ = writeln!(s, "        pub const SHARED_CODE: (u32, u32) = {};", pair(&g.plan.shared_code));
    let _ = writeln!(s, "        pub const KERNEL_RAM: (u32, u32) = {};", pair(&g.plan.kernel_ram));
    let _ = writeln!(s, "        /// The Kernel's peripheral intervals (R16.2): the PPB, then the Kernel-owned peripherals.");
    let _ = writeln!(
        s,
        "        pub const KERNEL_WINDOWS: [(u32, u32); {}] = [{}];",
        g.plan.kernel_windows.len(),
        g.plan.kernel_windows.iter().map(|w| format!("(0x{:08x}, 0x{:x})", w.base, 1u64 << w.size_log2)).collect::<Vec<_>>().join(", ")
    );
    let _ = writeln!(s, "        /// Each Partition's code and RAM region, and its stack size (the stack");
    let _ = writeln!(s, "        /// is the bottom of its RAM; the word below it is outside every view, R16.5).");
    let _ = writeln!(s, "        pub const CODE: [(u32, u32); PARTITIONS] = [{}];", g.plan.partitions.iter().map(|q| pair(&q.code)).collect::<Vec<_>>().join(", "));
    let _ = writeln!(s, "        pub const RAM: [(u32, u32); PARTITIONS] = [{}];", g.plan.partitions.iter().map(|q| pair(&q.ram)).collect::<Vec<_>>().join(", "));
    let _ = writeln!(s, "        pub const STACK: [u32; PARTITIONS] = [{}];", g.plan.partitions.iter().map(|q| q.stack.to_string()).collect::<Vec<_>>().join(", "));
    let _ = writeln!(s, "        /// Each Partition's peripheral windows, `(0, 0)` past its count.");
    let _ = writeln!(s, "        pub const WINDOWS: [[(u32, u32); {}]; PARTITIONS] = [", crate::layout::MAX_WINDOWS);
    for q in &g.plan.partitions {
        let mut w: Vec<String> = q.windows.iter().map(|w| format!("(0x{:08x}, 0x{:x})", w.base, 1u64 << w.size_log2)).collect();
        while w.len() < crate::layout::MAX_WINDOWS {
            w.push("(0, 0)".to_string());
        }
        let _ = writeln!(s, "            [{}],", w.join(", "));
    }
    let _ = writeln!(s, "        ];");
    let _ = writeln!(s, "    }}");
    let _ = writeln!(s, "}}");
    // Task 21.2 (R38.1, R42.1): the payload type of each Endpoint a Task of
    // this Partition is bound to fits the declared payload, and the
    // Kernel's word copies cover it (`rsk::Plain` bounds the type itself).
    for e in g.endpoints.iter().filter(|e| e.roles.iter().any(|(_, ti)| part.tasks.contains(ti)) && e.protocol.is_none()) {
        let _ = writeln!(s, "const _: () = assert!(::core::mem::size_of::<{}>() <= {}, \"the payload of Endpoint `{}` exceeds its declared `payload` bytes (R38.1)\");", e.ty, e.payload, e.name);
    }
    let _ = writeln!(s, "pub mod rsk_ctx {{");
    for &t in &part.tasks {
        let task = &g.tasks[t];
        let _ = writeln!(s, "    /// The Context of Task `{}` (Priority {}).", task.id, task.priority);
        let _ = writeln!(s, "    pub struct {} {{", ctx_name(&task.name));
        for &r in &task.resources {
            let res = &g.resources[r];
            let _ = writeln!(s, "        pub {}: ::rsk::Shared<'static, {}>,", res.name, res.ty);
        }
        for sg in &task.raises {
            let _ = writeln!(s, "        /// Release_Signal `{}.{sg}` (R10.5).", part.name);
            let _ = writeln!(s, "        pub {sg}: ::rsk::Signal,");
        }
        for e in g.endpoints.iter().filter(|e| e.roles.iter().any(|(_, ti)| *ti == t)) {
            let role = e.roles.iter().find(|(_, ti)| *ti == t).map(|(n, _)| n.as_str()).unwrap_or("");
            match &e.protocol {
                None => {
                    let ri = e.roles.iter().position(|(r, _)| r == role).unwrap_or(0);
                    let validated = e.validators.get(ri).map_or(false, |v| v.iter().any(|(l, _)| l.is_none()));
                    let _ = writeln!(s, "        /// Role `{role}` of Endpoint `{}` (task 21.2; R38.1, R40.1): {} messages of `{}` each way{}.", e.name, e.capacity, e.ty, if validated { ", received through the role's validation function (R42.4)" } else { "" });
                    if validated {
                        let _ = writeln!(s, "        pub {}: ::rsk::Endpoint<{}, {}, super::rsk_validate::{}_{role}>,", e.name, e.ty, e.payload / 4, e.name);
                    } else {
                        let _ = writeln!(s, "        pub {}: ::rsk::Endpoint<{}, {}>,", e.name, e.ty, e.payload / 4);
                    }
                }
                Some(pname) => {
                    // Task 21.3: the RoleSlot of the Protocol's projection onto
                    // the role (the API is `rsk_roles::<endpoint>_<role>`).
                    let proj = e.projections.iter().find(|(r, _)| r == role).map(|(_, l)| l.as_str()).unwrap_or("");
                    let _ = writeln!(s, "        /// Role `{role}` of Endpoint `{}` under Protocol `{pname}` (tasks 21.1, 21.3; R38.3, R38.7): the slot of its state between Jobs, `{proj}`; bound k = {} (R41.1), capacity {}.", e.name, e.k, e.capacity);
                    let _ = writeln!(s, "        pub {}: ::rsk::RoleSlot<'static, super::rsk_roles::{}_{role}::State>,", e.name, e.name);
                }
            }
        }
        for st in &task.state {
            let _ = writeln!(s, "        /// Per-Task state `{}` (PR-25).", st.name);
            let _ = writeln!(s, "        pub {}: ::rsk::PerTask<'static, {}>,", st.name, st.ty);
        }
        let _ = writeln!(s, "    }}");
    }
    let _ = writeln!(s, "}}");
    // The App_Prover's view of the Partition (task 17.1, R46.4), compiled
    // under `cfg(creusot)` only: one logical invariant per Resource (the
    // declared closure, or `true`), a check that the initial value satisfies
    // it, and per Task the precondition that its Context's Resources carry
    // their invariants, which a Task body states with
    // `#[cfg_attr(creusot, rsk::creusot_std::macros::requires(rsk_spec::<task>_pre(&cx)))]`.
    let _ = writeln!(s, "#[cfg(creusot)]");
    let _ = writeln!(s, "#[allow(unused_imports, unused_variables)]");
    let _ = writeln!(s, "pub mod rsk_spec {{");
    let _ = writeln!(s, "    use ::rsk::creusot_std::prelude::*;");
    for &r in &part.resources {
        let res = &g.resources[r];
        let (param, body) = match &res.invariant {
            Some(closure) => split_closure(closure).unwrap_or(("_v".to_string(), "true".to_string())),
            None => ("_v".to_string(), "true".to_string()),
        };
        let _ = writeln!(s, "    /// The invariant of Resource `{}` (R46.4).", res.id);
        let _ = writeln!(s, "    #[logic(open)]");
        let param = if param.contains(':') { param } else { format!("{}: {}", param, res.ty) };
        let _ = writeln!(s, "    pub fn {}_inv({}) -> bool {{ pearlite! {{ {} }} }}", res.name, param, body);
        let _ = writeln!(s, "    /// The initial value of `{}` satisfies its invariant.", res.id);
        let _ = writeln!(s, "    pub fn {}_init_ok() {{", res.name);
        let _ = writeln!(s, "        let init: {} = {};", res.ty, res.init);
        let _ = writeln!(s, "        proof_assert!({}_inv(init));", res.name);
        let _ = writeln!(s, "    }}");
    }
    for &t in &part.tasks {
        let task = &g.tasks[t];
        let _ = writeln!(s, "    /// The precondition of `{}`'s body: its Resources carry their invariants.", task.id);
        let _ = writeln!(s, "    #[logic(open)]");
        let _ = writeln!(s, "    pub fn {}_pre(cx: &super::rsk_ctx::{}) -> bool {{", task.name, ctx_name(&task.name));
        let mut terms: Vec<String> = Vec::new();
        for &r in &task.resources {
            let res = &g.resources[r];
            terms.push(format!("(forall<x: {}> (*cx).{}@[x] == {}_inv(x))", res.ty, res.name, res.name));
        }
        if terms.is_empty() {
            terms.push("true".to_string());
        }
        let _ = writeln!(s, "        pearlite! {{ {} }}", terms.join(" && "));
        let _ = writeln!(s, "    }}");
    }
    let _ = writeln!(s, "}}");
    let _ = writeln!(s, "#[cfg(not(creusot))]");
    let _ = writeln!(s, "pub mod rsk_jobs {{");
    for &t in &part.tasks {
        let task = &g.tasks[t];
        let sites = cs_sites(g, t);
        let _ = writeln!(s, "    /// Job wrapper of `{}` (vector {}; Critical_Section sites: {}).", task.id, task.vector(), if sites.is_empty() { "none".to_string() } else { sites.join(", ") });
        // Never inlined across crates: a small wrapper would otherwise be copied
        // into the system crate's object and placed in the Kernel's text, where
        // the unprivileged Job cannot fetch it (seen on the nRF52840-DK, 2026-10-29;
        // the Link_Checker reports it as R16.3).
        let _ = writeln!(s, "    #[inline(never)]");
        let _ = writeln!(s, "    pub fn {}() {{", task.name);
        // `let () =`: the body is a synchronous function returning `()` (an
        // `async fn` returns a future and fails to compile here, PR-09).
        let _ = writeln!(s, "        let () = super::{}(super::rsk_ctx::{} {{", task.name, ctx_name(&task.name));
        for &r in &task.resources {
            let res = &g.resources[r];
            let _ = writeln!(s, "            {}: ::rsk::Shared::new(&super::rsk_resources::{}, {}),", res.name, res.name.to_uppercase(), r);
        }
        let sigs = signals(g);
        for sg in &task.raises {
            let idx = sigs.iter().position(|(sp, n, _)| *sp == task.partition && n == sg).unwrap_or(0xFF);
            let _ = writeln!(s, "            {sg}: ::rsk::Signal::new({idx}),");
        }
        for e in g.endpoints.iter().filter(|e| e.roles.iter().any(|(_, ti)| *ti == t)) {
            let role = e.roles.iter().position(|(_, ti)| *ti == t).unwrap_or(0);
            if e.protocol.is_some() {
                let _ = writeln!(s, "            {}: ::rsk::RoleSlot::new(&super::rsk_state::{}_{}),", e.name, task.name.to_uppercase(), e.name.to_uppercase());
            } else {
                let _ = writeln!(s, "            {}: ::rsk::Endpoint::new({}, {}),", e.name, e.index, role);
            }
        }
        for st in &task.state {
            let _ = writeln!(s, "            {}: ::rsk::PerTask::new(&super::rsk_state::{}_{}),", st.name, task.name.to_uppercase(), st.name.to_uppercase());
        }
        let _ = writeln!(s, "        }});");
        // Task 21.3 (R41.2): a Job that returns with a RoleSlot empty failed to
        // store its role state: reported to the Health_Monitor.
        for (e, role) in protocol_roles(g, t) {
            let _ = writeln!(s, "        if super::rsk_state::{}_{}.with_unprivileged(|st| st.is_empty()) {{", task.name.to_uppercase(), e.name.to_uppercase());
            let _ = writeln!(s, "            // Role `{role}` of `{}`: the Job returned without storing its state (R41.2).", e.name);
            let _ = writeln!(s, "            ::rsk::report_protocol_violation();");
            let _ = writeln!(s, "        }}");
        }
        let _ = writeln!(s, "    }}");
    }
    let _ = writeln!(s, "}}");
    s
}

/// The summary's note of an Endpoint's validation functions and operation
/// counts (tasks 21.4 and 21.5).
fn validators_note(e: &crate::derive::GenEndpoint) -> String {
    let mut parts = Vec::new();
    for (i, (role, _)) in e.roles.iter().enumerate() {
        for (label, path) in e.validators.get(i).into_iter().flatten() {
            parts.push(match label {
                None => format!("{role} validates the payload with {path}"),
                Some(l) => format!("{role} validates {l} with {path}"),
            });
        }
        if let Some(n) = e.ops.get(i) {
            if *n != 1 {
                parts.push(format!("{role} performs up to {n} operations per Job"));
            }
        }
    }
    if parts.is_empty() { String::new() } else { format!("; {}", parts.join(", ")) }
}

/// The (Endpoint, role) pairs of Task `t` under a Protocol (task 21.3).
fn protocol_roles(g: &Generated, t: usize) -> Vec<(&crate::derive::GenEndpoint, String)> {
    g.endpoints
        .iter()
        .filter(|e| e.protocol.is_some())
        .filter_map(|e| e.roles.iter().find(|(_, ti)| *ti == t).map(|(r, _)| (e, r.clone())))
        .collect()
}

/// `|v: u32| v <= 1` -> ("v: u32", "v <= 1").
fn split_closure(closure: &str) -> Option<(String, String)> {
    let rest = closure.trim().strip_prefix('|')?;
    let (param, body) = rest.split_once('|')?;
    let param = param.trim();
    let body = body.trim();
    if param.is_empty() || body.is_empty() {
        return None;
    }
    Some((param.to_string(), body.to_string()))
}

/// The Release_Signals in Generated_Config order: (declaring Partition
/// index, name, bound Task index).
fn signals(g: &Generated) -> Vec<(usize, String, Option<usize>)> {
    let mut out = Vec::new();
    for (p, part) in g.partitions.iter().enumerate() {
        for name in &part.signals {
            let bound = g
                .tasks
                .iter()
                .find(|t| matches!(&t.source, Some(ReleaseSource::Signal(x)) if x == name))
                .map(|t| t.index);
            out.push((p, name.clone(), bound));
        }
    }
    out
}

/// `control` -> `Control`, `imu_read` -> `ImuRead`.
pub fn ctx_name(task: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for c in task.chars() {
        if c == '_' {
            upper = true;
            continue;
        }
        if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn archive(krate: &str) -> String {
    krate.replace('-', "_")
}

